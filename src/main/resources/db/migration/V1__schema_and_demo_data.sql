CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    full_name VARCHAR(160) NOT NULL
);

CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL UNIQUE,
    balance DECIMAL(14, 2) NOT NULL CHECK (balance >= 0),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_accounts_customer FOREIGN KEY (customer_id) REFERENCES customers(id)
);

CREATE TABLE savings_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    target_amount DECIMAL(14, 2) NOT NULL CHECK (target_amount > 0),
    balance DECIMAL(14, 2) NOT NULL CHECK (balance >= 0),
    CONSTRAINT fk_goals_account FOREIGN KEY (account_id) REFERENCES accounts(id)
);

CREATE TABLE savings_operations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_id BIGINT NOT NULL,
    type VARCHAR(20) NOT NULL CHECK (type IN ('DEPOSIT', 'WITHDRAWAL')),
    amount DECIMAL(14, 2) NOT NULL CHECK (amount > 0),
    occurred_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_operations_goal FOREIGN KEY (goal_id) REFERENCES savings_goals(id)
);

CREATE INDEX idx_savings_operations_goal_time ON savings_operations(goal_id, occurred_at);

